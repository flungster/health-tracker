    stroke_rate_max_spm  integer NULL CHECK (stroke_rate_max_spm IS NULL OR stroke_rate_max_spm > 0),
    split_500m_seconds   double precision NULL CHECK (split_500m_seconds IS NULL OR split_500m_seconds >= 0),
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    deleted_at           timestamptz NULL
);

CREATE TRIGGER rowing_activity_set_updated_at
    BEFORE UPDATE ON rowing_activity
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE rowing_activity IS
    'Rowing-specific metrics for activities with sport_type = rowing.';
COMMENT ON COLUMN rowing_activity.stroke_rate_avg_spm IS 'Average stroke rate in strokes per minute.';
COMMENT ON COLUMN rowing_activity.stroke_rate_min_spm IS 'Slowest stroke rate (spmin).';
COMMENT ON COLUMN rowing_activity.stroke_rate_max_spm IS 'Fastest stroke rate (spmin).';
COMMENT ON COLUMN rowing_activity.split_500m_seconds IS
    'Average 500m split in seconds (the standard rowing pace metric), when distance data exists.';

CREATE TABLE strength_activity (
    activity_id      uuid PRIMARY KEY REFERENCES activities (id) ON DELETE CASCADE,
    total_sets       integer NOT NULL DEFAULT 0 CHECK (total_sets >= 0),
    total_exercises  integer NOT NULL DEFAULT 0 CHECK (total_exercises >= 0),
    total_weight_kg  double precision NULL CHECK (total_weight_kg IS NULL OR total_weight_kg >= 0),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    deleted_at       timestamptz NULL
);

CREATE TRIGGER strength_activity_set_updated_at
    BEFORE UPDATE ON strength_activity
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE strength_activity IS
    'Strength-training summary metrics for activities with sport_type = strength.';
COMMENT ON COLUMN strength_activity.total_sets IS 'Total number of sets across all exercises.';
COMMENT ON COLUMN strength_activity.total_exercises IS 'Number of distinct exercises.';
COMMENT ON COLUMN strength_activity.total_weight_kg IS 'Total lifted volume in kg (sum of set weight x reps), when known.';

CREATE TABLE strength_exercise_sets (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id    uuid NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
    exercise_name  text NOT NULL,
    set_index      integer NOT NULL CHECK (set_index >= 1),
    reps           integer NULL CHECK (reps IS NULL OR reps > 0),
    weight_kg      double precision NULL CHECK (weight_kg IS NULL OR weight_kg >= 0),
    rest_seconds   integer NULL CHECK (rest_seconds IS NULL OR rest_seconds >= 0)
);

CREATE INDEX strength_exercise_sets_activity_idx ON strength_exercise_sets (activity_id);

COMMENT ON TABLE strength_exercise_sets IS
    'Per-set detail for strength activities. Immutable bulk data: no audit columns by design.';
COMMENT ON COLUMN strength_exercise_sets.exercise_name IS 'Exercise as recorded in the source (e.g. "Squat").';
COMMENT ON COLUMN strength_exercise_sets.set_index IS '1-based set number within the exercise.';
COMMENT ON COLUMN strength_exercise_sets.reps IS 'Reps performed (NULL for time-based sets).';
COMMENT ON COLUMN strength_exercise_sets.weight_kg IS 'Load in kilograms (NULL for bodyweight sets).';
COMMENT ON COLUMN strength_exercise_sets.rest_seconds IS 'Rest after the set, when the source provides it.';

