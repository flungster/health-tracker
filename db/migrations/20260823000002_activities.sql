    deleted_at    timestamptz NULL
);

CREATE TRIGGER cycling_activity_set_updated_at
    BEFORE UPDATE ON cycling_activity
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE cycling_activity IS
    'Cycling-specific metrics for activities with sport_type = cycling.';
COMMENT ON COLUMN cycling_activity.power_avg_w IS 'Average power in watts, from the file or trackpoints.';
COMMENT ON COLUMN cycling_activity.power_max_w IS 'Maximum power in watts, from the file or trackpoints.';

CREATE TABLE rowing_activity (
